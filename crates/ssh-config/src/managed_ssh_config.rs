use crate::json::{self, ConfigRecord, HostRecord};
use crate::{ManagedSshHost, SshConfigError, SshConfigStoreError};

/// The hosts Glasshouse manages. Stored as JSON (see [`SshConfigStore`](crate::SshConfigStore)) and rendered to
/// `~/.ssh/glasshouse.conf`, which `~/.ssh/config` includes at the top.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ManagedSshConfig {
    hosts: Vec<ManagedSshHost>,
}

impl ManagedSshConfig {
    /// No hosts.
    pub fn new() -> Self {
        Self::default()
    }

    /// Adds each host in turn, validating it and checking its aliases are unique.
    pub fn with_hosts(
        hosts: impl IntoIterator<Item = ManagedSshHost>,
    ) -> Result<Self, SshConfigError> {
        let mut config = Self::new();
        for host in hosts {
            config.upsert(&host, None)?;
        }
        Ok(config)
    }

    /// Parses the stored JSON. Re-validates on load: the JSON is a plain file anyone running as you can edit, and
    /// its values are written into ssh_config.
    pub fn from_json(json: &[u8]) -> Result<Self, SshConfigStoreError> {
        let record: ConfigRecord = serde_json::from_slice(json)?;
        Ok(Self::with_hosts(
            record.hosts.into_iter().map(ManagedSshHost::from),
        )?)
    }

    /// The JSON [`from_json`](Self::from_json) reads, formatted like Swift's pretty-printed, key-sorted
    /// `JSONEncoder` output.
    pub fn to_json(&self) -> Result<String, SshConfigStoreError> {
        let record = ConfigRecord {
            hosts: self.hosts.iter().map(HostRecord::from).collect(),
        };
        Ok(json::to_swift_json(&record)?)
    }

    /// The managed hosts, in order.
    pub fn hosts(&self) -> &[ManagedSshHost] {
        &self.hosts
    }

    /// Adds `host`. With `replacing`, replaces the entry with that alias instead (an edit, which may rename it).
    /// Every alias a host writes (`myserver`, and `myserver-key` with a security key) must be unique,
    /// ignoring ASCII case as OpenSSH does.
    pub fn upsert(
        &mut self,
        host: &ManagedSshHost,
        replacing: Option<&str>,
    ) -> Result<(), SshConfigError> {
        let host = host.validated()?;
        let index = replacing
            .and_then(|original| self.hosts.iter().position(|other| other.alias == original));
        let names = host.aliases();
        for (i, other) in self.hosts.iter().enumerate() {
            if Some(i) == index {
                continue;
            }
            // OpenSSH matches Host patterns case-insensitively: `prod` and `PROD` are one host,
            // and the first block's settings would win for both.
            if let Some(clash) = other
                .aliases()
                .into_iter()
                .find(|alias| names.iter().any(|name| name.eq_ignore_ascii_case(alias)))
            {
                return Err(SshConfigError::DuplicateAlias(clash));
            }
        }
        match index {
            Some(index) => self.hosts[index] = host,
            None => self.hosts.push(host),
        }
        Ok(())
    }

    /// Removes the host called `alias`, if there is one.
    pub fn remove(&mut self, alias: &str) {
        self.hosts.retain(|host| host.alias != alias);
    }

    /// Hosts whose Secure Enclave key or security key is `~/.ssh/<key_name>`.
    pub fn hosts_using_key(&self, key_name: &str) -> Vec<&ManagedSshHost> {
        self.hosts
            .iter()
            .filter(|host| {
                host.key_name == key_name
                    || host
                        .security_key
                        .as_ref()
                        .is_some_and(|key| key.key_name == key_name)
            })
            .collect()
    }

    /// Contents of `~/.ssh/glasshouse.conf`.
    pub fn render_include_file(&self) -> String {
        let mut text = String::from(
            "# Generated by Glasshouse (Settings › SSH Keys). Changes made here are overwritten.
# Each host signs only with its Secure Enclave key, so every login asks for Touch ID.
# An \"-key\" entry signs only with a security key, so every login needs a tap on it.
#   IdentityAgent none          keys held by ssh-agent are never offered
#   PubkeyAcceptedAlgorithms    other keys, such as IdentityFile lines under Host *, are skipped
",
        );
        for host in &self.hosts {
            text.push('\n');
            text += &host.config_block();
        }
        text
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::SecurityKey;
    use crate::ssh_config_text;
    use crate::test_support::myserver;

    #[test]
    fn include_file_has_a_header_then_each_host() {
        let mut config = ManagedSshConfig::new();
        assert!(
            config
                .render_include_file()
                .starts_with("# Generated by Glasshouse")
        );
        assert!(ssh_config_text::host_aliases(&config.render_include_file()).is_empty());
        config.upsert(&myserver(), None).unwrap();
        config
            .upsert(
                &ManagedSshHost::new("gh", "github.com", Some("git"), None, "glasshouse"),
                None,
            )
            .unwrap();
        let text = config.render_include_file();
        let tail = format!(
            "\n{}\n{}",
            myserver().config_block(),
            config.hosts()[1].config_block()
        );
        assert!(text.ends_with(&tail));
        assert_eq!(ssh_config_text::host_aliases(&text), ["myserver", "gh"]);
    }

    #[test]
    fn upsert_should_refuse_an_alias_that_differs_only_in_case() {
        let mut config = ManagedSshConfig::new();
        config.upsert(&myserver(), None).unwrap();
        let mut shouting = myserver();
        shouting.alias = "MYSERVER".into();
        assert_eq!(
            config.upsert(&shouting, None),
            Err(SshConfigError::DuplicateAlias("myserver".into()))
        );
    }

    #[test]
    fn adds_edits_renames_and_removes() {
        let mut config = ManagedSshConfig::new();
        config.upsert(&myserver(), None).unwrap();
        assert_eq!(
            config.upsert(&myserver(), None),
            Err(SshConfigError::DuplicateAlias("myserver".into()))
        );

        let mut edited = myserver();
        edited.port = Some(2222);
        config.upsert(&edited, Some("myserver")).unwrap();
        assert_eq!(config.hosts(), [edited.clone()]);

        edited.alias = "prod".into();
        config.upsert(&edited, Some("myserver")).unwrap();
        assert_eq!(
            config
                .hosts()
                .iter()
                .map(|h| h.alias.as_str())
                .collect::<Vec<_>>(),
            ["prod"]
        );

        config.upsert(&myserver(), None).unwrap();
        assert_eq!(
            config.upsert(&edited, Some("myserver")),
            Err(SshConfigError::DuplicateAlias("prod".into()))
        );

        assert_eq!(config.hosts_using_key("glasshouse").len(), 2);
        config.remove("prod");
        assert_eq!(
            config
                .hosts()
                .iter()
                .map(|h| h.alias.as_str())
                .collect::<Vec<_>>(),
            ["myserver"]
        );
    }

    #[test]
    fn round_trips_through_json() {
        let host = myserver()
            .with_security_key(Some(SecurityKey::with_provider("sk", "/opt/lib/sk.dylib")))
            .with_backup_keys(vec![crate::test_support::key_line(
                "ssh-ed25519",
                "laptop",
                2,
            )]);
        let other = ManagedSshHost::new("gh", "github.com", None, None, "glasshouse");
        let config = ManagedSshConfig::with_hosts([host, other]).unwrap();
        let decoded = ManagedSshConfig::from_json(config.to_json().unwrap().as_bytes()).unwrap();
        assert_eq!(decoded, config);
    }

    #[test]
    fn writes_json_like_swifts_pretty_sorted_encoder() {
        let host = myserver().with_security_key(Some(SecurityKey::new("sk")));
        let config = ManagedSshConfig::with_hosts([host.clone()]).unwrap();
        let json = config.to_json().unwrap();
        assert_eq!(
            json,
            r#"{
  "hosts" : [
    {
      "alias" : "myserver",
      "backupKeys" : [],
      "hostName" : "10.0.0.5",
      "keyName" : "glasshouse",
      "port" : 22,
      "securityKey" : {
        "keyName" : "sk",
        "provider" : "internal"
      },
      "user" : "you"
    }
  ]
}"#
        );
        let with_path = ManagedSshConfig::with_hosts([
            host.with_security_key(Some(SecurityKey::with_provider("sk", "/opt/sk.dylib")))
        ])
        .unwrap();
        let json = with_path.to_json().unwrap();
        assert!(json.contains(r#""provider" : "\/opt\/sk.dylib""#));
        assert_eq!(
            ManagedSshConfig::from_json(json.as_bytes()).unwrap(),
            with_path
        );
    }

    #[test]
    fn refuses_a_hand_edited_file_with_injected_values() {
        let json = r#"{"hosts":[{"alias":"x\n  ProxyCommand id","hostName":"h","keyName":"k"}]}"#;
        assert!(matches!(
            ManagedSshConfig::from_json(json.as_bytes()),
            Err(SshConfigStoreError::Config(SshConfigError::InvalidAlias(_)))
        ));
        let duplicates = concat!(
            r#"{"hosts":[{"alias":"a","hostName":"h","keyName":"k"},"#,
            r#"{"alias":"a","hostName":"i","keyName":"k"}]}"#
        );
        assert!(matches!(
            ManagedSshConfig::from_json(duplicates.as_bytes()),
            Err(SshConfigStoreError::Config(SshConfigError::DuplicateAlias(alias))) if alias == "a"
        ));
    }

    #[test]
    fn loads_hosts_saved_before_these_fields_existed() {
        let json =
            r#"{"hosts":[{"alias":"myserver","hostName":"10.0.0.5","keyName":"glasshouse"}]}"#;
        let config = ManagedSshConfig::from_json(json.as_bytes()).unwrap();
        assert!(config.hosts()[0].backup_keys.is_empty());
        assert_eq!(config.hosts()[0].security_key, None);
    }

    #[test]
    fn aliases_stay_unique_across_entries() {
        let mut config = ManagedSshConfig::new();
        let a = ManagedSshHost::new("a", "h", None, None, "k")
            .with_security_key(Some(SecurityKey::new("sk")));
        config.upsert(&a, None).unwrap();
        assert_eq!(
            config.upsert(&ManagedSshHost::new("a-key", "h", None, None, "k"), None),
            Err(SshConfigError::DuplicateAlias("a-key".into()))
        );
        assert_eq!(
            config
                .hosts_using_key("sk")
                .iter()
                .map(|h| h.alias.as_str())
                .collect::<Vec<_>>(),
            ["a"]
        );
        let aliases: Vec<String> = config
            .hosts()
            .iter()
            .flat_map(ManagedSshHost::aliases)
            .collect();
        let conflicts = ssh_config_text::conflicts("Host a-key\n    User other\n", &aliases);
        assert_eq!(
            conflicts
                .iter()
                .map(|c| c.alias.as_str())
                .collect::<Vec<_>>(),
            ["a-key"]
        );
    }
}
