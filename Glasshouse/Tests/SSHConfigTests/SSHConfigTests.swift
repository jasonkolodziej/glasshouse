@Suite("Editing ~/.ssh/config")
struct MainConfigTextTests {
    @Test func installsTheIncludeAboveEverythingElse() throws {
        let original = try fixture()
        #expect(SSHConfigText.includeStatus(in: original) == .missing)

        let updated = SSHConfigText.installingInclude(in: original)
        #expect(updated.hasPrefix(SSHConfigText.includeBlock + "\n"))
        #expect(updated.hasSuffix(original))
        #expect(SSHConfigText.includeStatus(in: updated) == .active)
        #expect(SSHConfigText.installingInclude(in: updated) == updated)
    }

    @Test func removingRestoresTheOriginalExactly() throws {
        let original = try fixture()
        #expect(SSHConfigText.removingInclude(from: SSHConfigText.installingInclude(in: original)) == original)
        #expect(SSHConfigText.installingInclude(in: "") == SSHConfigText.includeBlock)
        #expect(SSHConfigText.removingInclude(from: SSHConfigText.includeBlock) == "")
    }

    @Test func movesABlockThatEndedUpBelowAHostLine() throws {
        let misplaced = try fixture() + "\n" + SSHConfigText.includeBlock
        guard case .inactive(let line) = SSHConfigText.includeStatus(in: misplaced) else {
            Issue.record("expected .inactive"); return
        }
        #expect(SSHConfigText.lines(misplaced)[line - 1] == "Include ~/.ssh/glasshouse.conf")

        let fixed = SSHConfigText.installingInclude(in: misplaced)
        #expect(SSHConfigText.includeStatus(in: fixed) == .active)
        #expect(fixed.components(separatedBy: SSHConfigText.beginMarker).count == 2)
    }

    @Test func keepsWindowsLineEndings() throws {
        let original = try fixture().replacingOccurrences(of: "\n", with: "\r\n")
        let updated = SSHConfigText.installingInclude(in: original)
        #expect(updated.hasSuffix(original))
        #expect(SSHConfigText.includeStatus(in: updated) == .active)
        #expect(SSHConfigText.hostAliases(in: original) == ["myserver", "myserver.local"])
        #expect(SSHConfigText.removingInclude(from: updated) == original)
    }

    @Test func acceptsAHandWrittenIncludeAtTheTop() {
        #expect(SSHConfigText.includeStatus(in: "Include glasshouse.conf\nHost a\n") == .active)
        #expect(SSHConfigText.includeStatus(in: "Host a\n  Include ~/.ssh/glasshouse.conf\n") == .inactive(line: 2))
    }

    @Test func findsOtherBlocksForAManagedAlias() throws {
        let text = SSHConfigText.installingInclude(in: try fixture())
        let lines = SSHConfigText.lines(text)
        let expected = lines.indices.filter { lines[$0] == "Host myserver" }.map { $0 + 1 }
        #expect(expected.count == 2)
        #expect(SSHConfigText.conflicts(in: text, aliases: ["myserver"]).map(\.line) == expected)
        #expect(SSHConfigText.conflicts(in: text, aliases: ["elsewhere"]).isEmpty)
    }

    @Test func readsAliasesAndIncludes() throws {
        let text = try fixture()
        #expect(SSHConfigText.hostAliases(in: text) == ["myserver", "myserver.local"])
        #expect(SSHConfigText.includePatterns(in: text) == ["~/.ssh/arc-slurm.conf"])
    }

    @Test(arguments: [
        ("  HOST=a b", "host", ["a", "b"]),
        ("\tIdentityFile \"~/My Keys/id\" # work", "identityfile", ["~/My Keys/id"]),
        ("Port = 22", "port", ["22"]),
    ])
    func parsesTheWaysSSHAllowsLinesToBeWritten(line: String, keyword: String, arguments: [String]) throws {
        let parsed = try #require(SSHConfigText.parse(line))
        #expect(parsed.keyword == keyword)
        #expect(parsed.arguments == arguments)
    }

    @Test func skipsCommentsAndBlankLinesAndStripsCarriageReturns() {
        #expect(SSHConfigText.parse("   # comment") == nil)
        #expect(SSHConfigText.parse("") == nil)
        #expect(SSHConfigText.directives(in: "Port 22\r\n").first?.arguments == ["22"])
    }
}

@Suite("Files on disk")
struct SSHConfigStoreTests {
    /// A throwaway home with `.ssh` and an Application Support stand-in.
    private struct Sandbox: ~Copyable {
        let home: URL
        let store: SSHConfigStore
        init() throws {
            home = FileManager.default.temporaryDirectory.appendingPathComponent("glasshouse-\(UUID().uuidString)")
            try FileManager.default.createDirectory(at: home.appendingPathComponent(".ssh"),
                                                    withIntermediateDirectories: true)
            store = SSHConfigStore(sshDirectory: home.appendingPathComponent(".ssh"),
                                   storeURL: home.appendingPathComponent("Support/Glasshouse/ssh-hosts.json"),
                                   homeDirectory: home)
        }
        deinit { try? FileManager.default.removeItem(at: home) }

        func write(_ text: String, _ path: String) throws {
            let url = home.appendingPathComponent(path)
            try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            try text.write(to: url, atomically: true, encoding: .utf8)
        }
        func read(_ path: String) throws -> String {
            try String(contentsOf: home.appendingPathComponent(path), encoding: .utf8)
        }
        func permissions(_ path: String) throws -> Int {
            try #require(FileManager.default.attributesOfItem(atPath: home.appendingPathComponent(path).path)[
                .posixPermissions] as? NSNumber).intValue
        }
    }

    @Test func savesTheHostListAndRegeneratesTheIncludeFile() throws {
        let box = try Sandbox()
        #expect(try box.store.load() == ManagedSSHConfig())

        let config = try ManagedSSHConfig(hosts: [myserver])
        try box.store.save(config)
        #expect(try box.store.load() == config)
        #expect(try box.read(".ssh/glasshouse.conf") == config.renderIncludeFile())
        #expect(try box.permissions(".ssh/glasshouse.conf") == 0o600)
        #expect(try box.permissions("Support/Glasshouse/ssh-hosts.json") == 0o600)
    }

    @Test func createsAMissingConfigWithJustTheInclude() throws {
        let box = try Sandbox()
        #expect(box.store.includeStatus() == .missing)
        try box.store.installInclude()
        #expect(try box.read(".ssh/config") == SSHConfigText.includeBlock)
        #expect(try box.permissions(".ssh/config") == 0o600)
        #expect(!FileManager.default.fileExists(atPath: box.store.backupURL.path))
        #expect(box.store.includeStatus() == .active)
    }

    @Test func backsUpAnExistingConfigOnceAndKeepsItsPermissions() throws {
        let box = try Sandbox()
        let original = try fixture()
        try box.write(original, ".ssh/config")
        try FileManager.default.setAttributes([.posixPermissions: NSNumber(value: 0o644)],
                                              ofItemAtPath: box.store.mainConfigURL.path)

        try box.store.installInclude()
        #expect(try box.read(".ssh/config") == SSHConfigText.installingInclude(in: original))
        #expect(try box.read(".ssh/config.glasshouse-backup") == original)
        #expect(try box.permissions(".ssh/config") == 0o644)

        try box.write("# changed later\n", ".ssh/config")
        try box.store.installInclude()
        #expect(try box.read(".ssh/config.glasshouse-backup") == original)
    }

    @Test func writesThroughASymlinkedConfig() throws {
        let box = try Sandbox()
        try box.write("Host a\n", "dotfiles/ssh_config")
        try FileManager.default.createSymbolicLink(at: box.store.mainConfigURL,
                                                   withDestinationURL: box.home.appendingPathComponent("dotfiles/ssh_config"))
        try box.store.installInclude()
        #expect(try FileManager.default.destinationOfSymbolicLink(atPath: box.store.mainConfigURL.path)
                .hasSuffix("dotfiles/ssh_config"))
        #expect(try box.read("dotfiles/ssh_config") == SSHConfigText.includeBlock + "\nHost a\n")
    }

    @Test func findsOnlySecureEnclaveKeyHandles() throws {
        let box = try Sandbox()
        try box.write("handle", ".ssh/glasshouse")
        try box.write("sk-ecdsa-sha2-nistp256@openssh.com AAAAInNr you@mac\n", ".ssh/glasshouse.pub")
        try box.write("key", ".ssh/id_ed25519")
        try box.write("ssh-ed25519 AAAAC3Nz you@mac\n", ".ssh/id_ed25519.pub")
        try box.write("sk-ecdsa-sha2-nistp256@openssh.com AAAAInNr orphan\n", ".ssh/orphan.pub")

        let keys = box.store.secureEnclaveKeys()
        #expect(keys.map(\.name) == ["glasshouse"])
        #expect(keys.first?.comment == "you@mac")
        #expect(keys.first?.publicKey == "sk-ecdsa-sha2-nistp256@openssh.com AAAAInNr you@mac")
    }

    @Test func findsSecurityKeysAndReadsPublicHalves() throws {
        let box = try Sandbox()
        try box.write("handle", ".ssh/glasshouse")
        try box.write(keyLine(GlasshouseSSH.secureEnclaveAlgorithm, "you@mac") + "\n", ".ssh/glasshouse.pub")
        try box.write("handle", ".ssh/id_ed25519_sk")
        try box.write(keyLine("sk-ssh-ed25519@openssh.com", "yubikey", seed: 3) + "\n", ".ssh/id_ed25519_sk.pub")

        #expect(box.store.securityKeyFiles().map(\.name) == ["glasshouse", "id_ed25519_sk"])
        #expect(box.store.securityKeyFiles().map(\.type) == [GlasshouseSSH.secureEnclaveAlgorithm, "sk-ssh-ed25519@openssh.com"])
        #expect(box.store.secureEnclaveKeys().map(\.name) == ["glasshouse"])
        #expect(try box.store.publicKey(named: "id_ed25519_sk").comment == "yubikey")
        #expect(throws: SSHConfigError.missingPublicKey("nope")) { try box.store.publicKey(named: "nope") }
        #expect(throws: SSHConfigError.missingPublicKey("../x")) { try box.store.publicKey(named: "../x") }
    }

    @Test func followsIncludesForHostAliases() throws {
        let box = try Sandbox()
        try box.write(SSHConfigText.includeBlock + "\nInclude config.d/*.conf\nInclude ~/.ssh/config\nHost top\n",
                      ".ssh/config")
        try box.store.save(ManagedSSHConfig(hosts: [myserver]))
        try box.write("Host b2\n", ".ssh/config.d/b.conf")
        try box.write("Host a1 *.wild\n", ".ssh/config.d/a.conf")
        try box.write("Host skipped\n", ".ssh/config.d/notes.txt")

        #expect(box.store.hostAliases() == ["top", "myserver", "a1", "b2"])
    }

    @Test func reportsConflictsInTheRealFile() throws {
        let box = try Sandbox()
        try box.write(try fixture(), ".ssh/config")
        let conflicts = box.store.conflicts(for: try ManagedSSHConfig(hosts: [myserver]))
        #expect(conflicts.count == 2)
        #expect(conflicts.allSatisfy { $0.alias == "myserver" })
    }
}

@Suite("Setup scripts")
struct ScriptTests {
    private let touchIDKey = try! SSHPublicKey(parsing: keyLine(GlasshouseSSH.secureEnclaveAlgorithm, "you@mac", seed: 1))
    private let backup = keyLine("ssh-ed25519", "laptop", seed: 2)

    @Test func installScriptChecksTheEntryThenInstallsWithTheUsualLogin() throws {
        let script = try GlasshouseSSHScripts.installKeys(on: myserver, touchIDKey: touchIDKey, securityKey: nil)
        #expect(script.contains("ssh -G 'myserver' | grep -qx 'pubkeyacceptedalgorithms sk-ecdsa-sha2-nistp256@openssh.com'"))
        #expect(script.contains("ssh -o IdentityAgent=SSH_AUTH_SOCK -o IdentitiesOnly=no"))
        #expect(script.contains("-o PubkeyAcceptedAlgorithms=+sk-ecdsa-sha2-nistp256@openssh.com 'myserver' 'sh -s' <<'GLASSHOUSE_REMOTE'"))
        #expect(script.contains("\nGLASSHOUSE_REMOTE\n"))
        #expect(script.contains("if ssh 'myserver' true;"))
        #expect(script.contains("(you@10.0.0.5:22)"))
        #expect(script.contains("echo '  - Touch ID key ~/.ssh/glasshouse'"))
    }

    @Test func offersToRemoveKeysOnlyWhenTheHostHasABackup() throws {
        let without = try GlasshouseSSHScripts.installKeys(on: myserver, touchIDKey: touchIDKey, securityKey: nil)
        #expect(!without.contains("read -r -p"))
        #expect(without.contains("has no backup key"))

        var host = myserver
        host.backupKeys = [backup]
        let with = try GlasshouseSSHScripts.installKeys(on: host, touchIDKey: touchIDKey, securityKey: nil)
        #expect(with.contains("read -r -p \"Remove them from myserver?"))
        #expect(with.contains("ssh 'myserver' \"sh -s $blobs\" <<'GLASSHOUSE_REMOVE'"))
        #expect(with.hasSuffix("\nGLASSHOUSE_REMOVE"))
        #expect(with.contains("echo '  - backup key laptop (ssh-ed25519)'"))
    }

    @Test func installsTheSecurityKeyAlongsideAndCountsItAsABackup() throws {
        var host = myserver
        host.securityKey = .init(keyName: "id_ed25519_sk")
        let securityKey = try SSHPublicKey(parsing: keyLine("sk-ssh-ed25519@openssh.com", "yubikey", seed: 3))
        let script = try GlasshouseSSHScripts.installKeys(on: host, touchIDKey: touchIDKey, securityKey: securityKey)
        #expect(script.contains("echo '  - security key ~/.ssh/id_ed25519_sk'"))
        #expect(script.contains("read -r -p"))
    }

    @Test func refusesAKeyThatIsNotASecureEnclaveKey() throws {
        let plain = try SSHPublicKey(parsing: backup)
        #expect(throws: SSHConfigError.missingPublicKey("glasshouse")) {
            try GlasshouseSSHScripts.installKeys(on: myserver, touchIDKey: plain, securityKey: nil)
        }
        #expect(throws: SSHConfigError.self) {
            try GlasshouseSSHScripts.installKeys(on: ManagedSSHHost(alias: "-x", hostName: "h", keyName: "k"),
                                                 touchIDKey: touchIDKey, securityKey: nil)
        }
    }

    @Test func createKeyScriptNeverOverwritesAKey() throws {
        let script = try GlasshouseSSHScripts.createSecureEnclaveKey(name: "work")
        #expect(script.contains("if [ -e ~/.ssh/work ] || [ -e ~/.ssh/work.pub ]; then"))
        #expect(script.contains("sc_auth create-ctk-identity -l work -k p-256-ne -t bio"))
        #expect(script.contains("mv id_ecdsa_sk_rk ~/.ssh/work && mv id_ecdsa_sk_rk.pub ~/.ssh/work.pub"))
        #expect(throws: SSHConfigError.invalidKeyName("../id_rsa")) {
            try GlasshouseSSHScripts.createSecureEnclaveKey(name: "../id_rsa")
        }
    }

    @Test func quotesForTheShell() {
        #expect(GlasshouseSSHScripts.shellQuote("it's") == #"'it'\''s'"#)
    }
}

/// Runs the server-side scripts with /bin/sh against a throwaway home, the way `ssh host 'sh -s'` runs them.
@Suite("Server-side scripts")
struct RemoteScriptTests {
    private let seKey = try! SSHPublicKey(parsing: keyLine(GlasshouseSSH.secureEnclaveAlgorithm, "you@mac", seed: 1))
    private let backup = try! SSHPublicKey(parsing: keyLine("ssh-ed25519", "laptop", seed: 2))
    private let everyday = keyLine("ssh-ed25519", "id_someID", seed: 4)
    private let yubikey = keyLine("sk-ssh-ed25519@openssh.com", "yubikey", seed: 5)
    private let noTouch = keyLine("sk-ssh-ed25519@openssh.com", "kiosk", seed: 6)

    private var items: [GlasshouseSSHScripts.InstallItem] {
        [.init(key: seKey, label: "Touch ID key ~/.ssh/glasshouse"), .init(key: backup, label: "backup key laptop")]
    }

    private func makeHome(authorizedKeys: String) throws -> URL {
        let home = FileManager.default.temporaryDirectory.appendingPathComponent("glasshouse-remote-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: home.appendingPathComponent(".ssh"), withIntermediateDirectories: true)
        try authorizedKeys.write(to: home.appendingPathComponent(".ssh/authorized_keys"), atomically: true, encoding: .utf8)
        return home
    }

    private func authorizedKeys(_ home: URL) throws -> String {
        try String(contentsOf: home.appendingPathComponent(".ssh/authorized_keys"), encoding: .utf8)
    }

    @Test func addsMissingKeysOnceAndListsKeysThatSkipTheTouch() throws {
        // The Secure Enclave key is already there under another comment; the file has no final newline.
        let existing = """
            # keys
            \(everyday)
            no-touch-required \(noTouch)
            \(yubikey)
            \(seKey.type) \(seKey.blob) old-comment
            """
        let home = try makeHome(authorizedKeys: existing)
        defer { try? FileManager.default.removeItem(at: home) }

        let output = try runShell(GlasshouseSSHScripts.remoteInstallScript(items: items), home: home)
        let lines = output.split(separator: "\n").map(String.init)
        #expect(lines.contains("present\tTouch ID key ~/.ssh/glasshouse"))
        #expect(lines.contains("added\tbackup key laptop"))
        let flagged = lines.filter { $0.hasPrefix("notouch\t") }.map { $0.split(separator: "\t").map(String.init) }
        #expect(flagged.map { $0[1] } == [try SSHPublicKey(parsing: everyday).blob, try SSHPublicKey(parsing: noTouch).blob])
        #expect(flagged.first?[3] == " id_someID")

        #expect(try authorizedKeys(home) == existing + "\n" + backup.line + "\n")
        _ = try runShell(GlasshouseSSHScripts.remoteInstallScript(items: items), home: home)
        #expect(try authorizedKeys(home) == existing + "\n" + backup.line + "\n")
        let permissions = try FileManager.default.attributesOfItem(
            atPath: home.appendingPathComponent(".ssh/authorized_keys").path)[.posixPermissions] as? NSNumber
        #expect(permissions?.intValue == 0o600)
    }

    @Test func createsTheFileWhenTheServerHasNone() throws {
        let home = try makeHome(authorizedKeys: "")
        defer { try? FileManager.default.removeItem(at: home) }
        try FileManager.default.removeItem(at: home.appendingPathComponent(".ssh"))
        let output = try runShell(GlasshouseSSHScripts.remoteInstallScript(items: items), home: home)
        #expect(!output.contains("notouch"))
        #expect(try authorizedKeys(home) == seKey.line + "\n" + backup.line + "\n")
    }

    @Test func removesOnlyTheChosenKeysAndKeepsACopy() throws {
        let existing = "\(everyday)\n\(seKey.line)\nno-touch-required \(noTouch)\n\(backup.line)\n"
        let home = try makeHome(authorizedKeys: existing)
        defer { try? FileManager.default.removeItem(at: home) }

        let blobs = try [everyday, noTouch].map { try SSHPublicKey(parsing: $0).blob }
        let output = try runShell(GlasshouseSSHScripts.remoteRemovalScript, home: home, arguments: blobs)
        #expect(output.hasPrefix("Removed 2 key(s)."))
        #expect(try authorizedKeys(home) == "\(seKey.line)\n\(backup.line)\n")
        let copies = try FileManager.default.contentsOfDirectory(atPath: home.appendingPathComponent(".ssh").path)
            .filter { $0.hasPrefix("authorized_keys.glasshouse-") }
        #expect(copies.count == 1)
        #expect(try String(contentsOf: home.appendingPathComponent(".ssh/\(copies[0])"), encoding: .utf8) == existing)
    }

    private func runShell(_ script: String, home: URL, arguments: [String] = []) throws -> String {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/bin/sh")
        process.arguments = ["-s"] + arguments
        process.environment = ["HOME": home.path, "PATH": "/usr/bin:/bin"]
        let input = Pipe(), output = Pipe()
        process.standardInput = input
        process.standardOutput = output
        process.standardError = output
        try process.run()
        input.fileHandleForWriting.write(Data(script.utf8))
        try input.fileHandleForWriting.close()
        let data = output.fileHandleForReading.readDataToEndOfFile()
        process.waitUntilExit()
        let text = String(decoding: data, as: UTF8.self)
        #expect(process.terminationStatus == 0, "\(text)")
        return text
    }
}

