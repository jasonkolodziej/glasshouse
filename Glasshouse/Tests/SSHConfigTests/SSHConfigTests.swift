        #expect(throws: SSHConfigError.duplicateAlias("myserver")) { try config.upsert(myserver) }

        var edited = myserver
        edited.port = 2222
        try config.upsert(edited, replacing: "myserver")
        #expect(config.hosts == [edited])

        edited.alias = "prod"
        try config.upsert(edited, replacing: "myserver")
        #expect(config.hosts.map(\.alias) == ["prod"])

