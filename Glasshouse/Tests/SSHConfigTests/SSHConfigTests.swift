@testable import SSHConfig

/// The ~/.ssh/config that logged in to `myserver` without Touch ID: `Host *` comes first and adds an agent-held
/// key, and a second `Host myserver` block adds it again.
private func fixture() throws -> String {
    let url = try #require(Bundle.module.url(forResource: "ssh-config", withExtension: "test", subdirectory: "Fixtures"))
    return try String(contentsOf: url, encoding: .utf8)
}

private let myserver = ManagedSSHHost(alias: "myserver", hostName: "10.0.0.5", user: "you", port: 22,
                                      keyName: "glasshouse")

@Suite("Managed host validation")
struct ManagedHostValidationTests {
    @Test func acceptsAnOrdinaryHost() throws {
        let host = try ManagedSSHHost(alias: " myserver ", hostName: "fe80::1", user: "", keyName: "glasshouse")
            .validated()
        #expect(host.alias == "myserver")
        #expect(host.user == nil)
        #expect(try ManagedSSHHost(alias: "db-1.prod", hostName: "db.example.com", user: "ops@corp", port: 2222,
                                   keyName: "work_key-2").validated().port == 2222)
    }

    @Test func rejectsValuesThatWouldAddDirectives() {
        #expect(throws: SSHConfigError.invalidAlias("myserver\n    ProxyCommand sh -c id")) {
            try ManagedSSHHost(alias: "myserver\n    ProxyCommand sh -c id", hostName: "h", keyName: "k").validated()
        }
        #expect(throws: SSHConfigError.invalidHostName("10.0.0.5 ProxyCommand")) {
            try ManagedSSHHost(alias: "a", hostName: "10.0.0.5 ProxyCommand", keyName: "k").validated()
        }
        #expect(throws: SSHConfigError.invalidUser("you\nProxyCommand")) {
            try ManagedSSHHost(alias: "a", hostName: "h", user: "you\nProxyCommand", keyName: "k").validated()
        }
        #expect(throws: SSHConfigError.invalidHostName("%h.evil")) {
            try ManagedSSHHost(alias: "a", hostName: "%h.evil", keyName: "k").validated()
        }
    }

    @Test func rejectsValuesThatLookLikeOptions() {
        #expect(throws: SSHConfigError.invalidAlias("-oProxyCommand=id")) {
            try ManagedSSHHost(alias: "-oProxyCommand=id", hostName: "h", keyName: "k").validated()
        }
        #expect(throws: SSHConfigError.invalidHostName("-p")) {
            try ManagedSSHHost(alias: "a", hostName: "-p", keyName: "k").validated()
        }
    }

    @Test(arguments: ["*", "my*", "!myserver", "a b", "", "my\"server"])
    func rejectsPatternsAndOddAliases(alias: String) {
        #expect(throws: SSHConfigError.self) {
            try ManagedSSHHost(alias: alias, hostName: "h", keyName: "k").validated()
        }
    }

    @Test(arguments: ["../id_rsa", "a/b", ".hidden", "glasshouse.pub", "-k", ""])
    func rejectsKeyNamesOutsideTheSSHDirectory(name: String) {
        #expect(!ManagedSSHHost.isValidKeyName(name))
    }

    @Test func checksThePortRange() throws {
        #expect(throws: SSHConfigError.invalidPort(0)) {
            try ManagedSSHHost(alias: "a", hostName: "h", port: 0, keyName: "k").validated()
        }
        #expect(throws: SSHConfigError.invalidPort(65_536)) {
            try ManagedSSHHost(alias: "a", hostName: "h", port: 65_536, keyName: "k").validated()
        }
        _ = try ManagedSSHHost(alias: "a", hostName: "h", port: 65_535, keyName: "k").validated()
    }
}

