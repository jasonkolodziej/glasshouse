import Foundation

/// The hosts Glasshouse manages. Stored as JSON (see `SSHConfigStore`) and rendered to `~/.ssh/glasshouse.conf`,
/// which `~/.ssh/config` includes at the top.
public struct ManagedSSHConfig: Codable, Equatable, Sendable {
    public private(set) var hosts: [ManagedSSHHost]

    public init() { hosts = [] }

    public init(hosts: [ManagedSSHHost]) throws {
        self.init()
        for host in hosts { try upsert(host) }
    }

    /// Re-validates on load: the JSON is a plain file anyone running as you can edit, and its values are
    /// written into ssh_config.
    public init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        try self.init(hosts: container.decode([ManagedSSHHost].self, forKey: .hosts))
    }

    /// Adds `host`. With `original`, replaces the entry with that alias instead (an edit, which may rename it).
    /// Every alias a host writes (`myserver`, and `myserver-key` with a security key) must be unique.
    public mutating func upsert(_ host: ManagedSSHHost, replacing original: String? = nil) throws {
        let host = try host.validated()
        let index = original.flatMap { original in hosts.firstIndex { $0.alias == original } }
        let names = Set(host.aliases)
        for (i, other) in hosts.enumerated() where i != index {
            if let clash = other.aliases.first(where: names.contains) { throw SSHConfigError.duplicateAlias(clash) }
        }
        if let index { hosts[index] = host } else { hosts.append(host) }
    }

    public mutating func remove(alias: String) {
        hosts.removeAll { $0.alias == alias }
    }

    public func hosts(usingKey keyName: String) -> [ManagedSSHHost] {
        hosts.filter { $0.keyName == keyName || $0.securityKey?.keyName == keyName }
    }

    /// Contents of `~/.ssh/glasshouse.conf`.
    public func renderIncludeFile() -> String {
        var text = """
        # Generated by Glasshouse (Settings › SSH Keys). Changes made here are overwritten.
        # Each host signs only with its Secure Enclave key, so every login asks for Touch ID.
        # An "-key" entry signs only with a security key, so every login needs a tap on it.
        #   IdentityAgent none          keys held by ssh-agent are never offered
        #   PubkeyAcceptedAlgorithms    other keys, such as IdentityFile lines under Host *, are skipped

        """
        for host in hosts { text += "\n" + host.configBlock }
        return text
    }
}
